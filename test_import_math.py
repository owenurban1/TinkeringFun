import math
radius = -8
compute_area = math.pi * radius ** 2
"""Computes the area of a circle with radius 5"""

compute_circumference = 2 * math.pi * radius
"""Computes the circumference of a circle with radius 5"""

print(compute_area)
print(compute_circumference)

